<?php
function convertday($var) {
switch ($var) {
    case "Mon":
        return "月";
        break;
    case "Tue":
        return "火";
        break;
    case "Wed":
        return "水";
        break;
    case "Thu":
        return "木";
        break;
    case "Fri":
        return "金";
        break;
    case "Sat":
        return "土";
        break;
    case "Sun":
        return "日";
        break;
}
}
